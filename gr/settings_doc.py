#!/usr/bin/env python3
"""settings_doc.py -- SETTINGS.md, the reference of every pd39route setting, generated from gr/pd39_settings.h
(2026-11-26, the user: "a full explanation of the run time options values and implications").

  python3 gr/settings_doc.py            write SETTINGS.md at the repository root
  python3 gr/settings_doc.py --check    exit 1 if SETTINGS.md differs from what the table generates (CI runs this
                                        through gr/settings_check.py, so the reference cannot drift from the router)

For each setting: its kind (what values it takes), its default (kDefaults), its one-line meaning (kTable), the words a
Text setting allows, and the value each standard settings file gives it. Standard library only.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'SETTINGS.md')
STR = r'"((?:[^"\\]|\\.)*)"'
# the settings files of the three standard flows, in the order they are layered
ENV_FILES = ['standard.env', 'fast08.env', 'speed08.env', 'standard24.env', 'fast24.env', 'standard25.env']
KINDS = {
    'Flag': '0 or 1',
    'OnIfSet': 'on when set; the value must be 1',
    'Int': 'a whole number',
    'Real': 'a number',
    'Number': 'a number (its own parser checks its range)',
    'List': 'several values, comma-separated (format in the meaning)',
    'Text': 'a word from a set',
    'File': 'a file or folder path',
}
FAMILIES = [  # name prefix -> which mechanism (the router generation that introduced it)
    ('GR_', 'Build and backend'), ('VROUTE_', 'Negotiation loop: rounds, prices, history (vroute)'),
    ('FR', 'Topology: Steiner trees (fr3route, fr4route)'), ('NV2ROUTE_', 'Via and wire history (nv2route)'),
    ('NV3ROUTE_', 'Giant nets (nv3route)'), ('NV11ROUTE_', 'Slow-tier search boxes (nv11route)'),
    ('PD1ROUTE_', 'Cost model (pd1route)'), ('PD2ROUTE_', 'Slow-tier acceptance (pd2route)'),
    ('PD3ROUTE_', 'Layer assignment (pd3route)'), ('PD4ROUTE_', 'Refinement stage (pd4route)'),
    ('PD5ROUTE_', 'Region stage (pd5route)'), ('PD6ROUTE_', 'Rip-up granularity (pd6route)'),
    ('PD7ROUTE_', 'Pin-aware layer assignment, wirelength recovery (pd7route)'), ('PD8ROUTE_', 'Tree rebuild (pd8route)'),
    ('PD9ROUTE_', 'Slow-tier pieces, stop point (pd9route)'), ('PD10ROUTE_', 'Pattern-first reroutes (pd10route)'),
    ('PD11ROUTE_', 'Batched pattern stage (pd11route)'), ('PD12ROUTE_', 'Plateau stops (pd12route)'),
    ('PD13ROUTE_', 'Box caps (pd13route)'), ('PD14ROUTE_', 'Work-gated plateau stop (pd14route)'),
    ('PD15ROUTE_', 'Detour trace (pd15route)'), ('PD16ROUTE_', 'Detour reclaim (pd16route)'),
    ('PD17ROUTE_', 'Reclaim avoidance (pd17route)'), ('PD18ROUTE_', 'Reclaim timing (pd18route)'),
    ('PD19ROUTE_', 'Reclaim fallback (pd19route)'), ('PD20ROUTE_', 'Fallback order (pd20route)'),
    ('PD21ROUTE_', 'Fallback limit (pd21route)'), ('PD22ROUTE_', 'Virtual capacity, parallel fallback (pd22route)'),
    ('PD23ROUTE_', 'Virtual capacity on path B (pd23route)'),
    ('PD33ROUTE_', 'ISPD 2024 / 2025: access points, score-aware layer assignment (pd33route)'),
    ('PD34ROUTE_', 'ISPD 2024 / 2025: score-aware 2D cost (pd34route)'),
    ('PD35ROUTE_', 'Memory and 3D pattern passes (pd35route)'), ('PD37ROUTE_', 'Threads (pd37route)'),
    ('PD38ROUTE_', 'Parallel slow tier and pattern stage (pd38route)'), ('PD39ROUTE_', 'pd39route\'s own settings'),
]


def table():
    head = open(os.path.join(HERE, 'pd39_settings.h')).read()
    rows = []
    for m in re.finditer(r'^\s*\{"([A-Z0-9_]+)", Kind::(\w+), ' + STR + r'(?:, ' + STR + r')?\},\s*$', head, re.M):
        rows.append({'name': m.group(1), 'kind': m.group(2), 'meaning': m.group(3).replace('\\"', '"'),
                     'allowed': m.group(4)})
    defaults = dict(re.findall(r'^\s*\{"([A-Z0-9_]+)", ' + STR + r'\},\s*$', head, re.M))
    for r in rows:
        r['default'] = defaults.get(r['name'], '?').replace('\\"', '"').replace("\\'", "'")
    return rows


def env_values():
    vals = {}
    for f in ENV_FILES:
        p = os.path.join(HERE, f)
        if not os.path.exists(p):
            continue
        for line in open(p):
            line = line.strip()
            if line and not line.startswith('#') and '=' in line:
                k, v = line.split('=', 1)
                vals.setdefault(k, []).append((f, v))
    return vals


def family(name):
    best = ('', 'Other')
    for p, t in FAMILIES:
        if name.startswith(p) and len(p) > len(best[0]):
            best = (p, t)
    return best[1]


def cell(s):
    return s.replace('|', '\\|')


def render():
    rows, env = table(), env_values()
    out = ['# pd39route settings reference', '',
           '<!-- Generated by gr/settings_doc.py from gr/pd39_settings.h. Do not edit by hand: change the table and '
           'rerun it (CI checks that this file is current). -->', '',
           f'Every setting `pd39route` reads: {len(rows)} in all. All are environment variables. A settings file '
           '(`gr/*.env`) is a list of them, one `NAME=value` per line. `USAGE.md` explains how the flows load them; '
           'load a file line by line, never by sourcing it in a shell (`fast08.env`\'s `PD39ROUTE_PORTFOLIO` holds `;`).', '',
           '- **Checked before any work.** A name with a known prefix that is not in this table, an `int` or `real` '
           'value that is not a number, a `flag` that is not 0 or 1, or a `text` word outside its set: each stops the '
           'run before it starts, with every problem listed (`gr/pd39_run.h`).',
           '- **Default** is the value used when the setting is unset. "unset (off)" means the mechanism runs only when '
           'the setting is given.',
           '- **Standard files** gives the value each standard flow\'s settings files set. The ISPD 2008 standard is '
           '`@standard.env @fast08.env`, and `@speed08.env` is layered after it. ISPD 2024 adds `@standard24.env '
           '@fast24.env` to `standard.env`; ISPD 2025 adds `@standard25.env` to those.',
           '- **Implications** of a value are in the Part named in each meaning: `HISTORY_COST_SWEEP.md` records what '
           'it was measured to do.',
           '- `./pd39route --settings` prints this table, with what the current environment sets.', '',
           '## Kinds', '', '| kind | value |', '|---|---|']
    out += [f'| {k.lower()} | {v} |' for k, v in KINDS.items()]
    groups = {}
    for r in rows:
        groups.setdefault(family(r['name']), []).append(r)
    order = [t for _, t in FAMILIES] + ['Other']
    for g in [t for t in order if t in groups]:
        out += ['', f'## {g}', '', '| setting | kind | default | meaning | standard files |', '|---|---|---|---|---|']
        for r in groups[g]:
            meaning = r['meaning'] + (f" Words: `{r['allowed'].replace('|', ', ')}`." if r['allowed'] else '')
            std = '<br>'.join(f'`{f}`: `{v}`' for f, v in env.get(r['name'], []))
            out.append(f"| `{r['name']}` | {r['kind'].lower()} | {cell(r['default'])} | {cell(meaning)} | {cell(std)} |")
    unknown = sorted(k for k in env if k not in {r['name'] for r in rows})
    if unknown:
        out += ['', 'Names set in the settings files that are not router settings: ' + ', '.join(unknown)]
    return '\n'.join(out) + '\n'


def main():
    text = render()
    if '--check' in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != text:
            print('settings_doc: SETTINGS.md is out of date; run python3 gr/settings_doc.py')
            return 1
        print('settings_doc: SETTINGS.md is current')
        return 0
    open(OUT, 'w').write(text)
    print(f'settings_doc: wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
