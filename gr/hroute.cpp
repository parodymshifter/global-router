// hroute.cpp
//
// A heuristic dispatcher, not a third algorithm from scratch: run nproute's
// fast tier (L/Z pattern candidates, its tuned pricing curve, selective
// rip-up, the cleanup pass) to full convergence first, then escalate only
// the nets still overflowed afterward to mroute's bounded Dijkstra search.
//
// Why per-net escalation rather than picking one algorithm for the whole
// design: mroute (stage 5, step 1) beat every prior router's overflow on
// adaptec1 but lost clearly on newblue1 and bigblue1 -- a real maze search
// finds routes a pattern menu structurally cannot on some congestion
// patterns, but costs 95-355s per benchmark against nproute's 5-22s, and
// there's no reliable way to tell in advance, from three benchmarks, which
// whole design favors which router. Escalating per net sidesteps that
// classification problem entirely: it doesn't need to guess which *design*
// favors maze search, it reactively finds exactly which *nets* the cheap
// tier is demonstrably failing on, which is precisely where mroute's
// structural advantage should matter, and leaves everything the cheap tier
// already solved alone.
//
// Architecture: nproute's shell and mroute's shell are both reproduced here
// (not included from those files -- they're each frozen, standalone
// comparison points per this project's convention) sharing one Usage/Prices
// model and one RoutedNet. Phase A runs the fast tier exactly as nproute
// does. Phase B marks whatever remains overflowed as `escalated` and
// continues the rip-up loop routing escalated nets with Dijkstra instead --
// once escalated, a net stays on the Dijkstra tier for the rest of the run;
// there is no reason to downgrade back to a smaller candidate menu once a
// real search has been paid for.
//
// A real bug on the way to this result, worth recording: the first version
// of phase B accepted every escalated net's Dijkstra reroute unconditionally,
// all in one round. On adaptec1, 53840 nets (30% of the design) escalated
// at once, and overflow spiked to 5.6 *million* before slowly recovering
// over many rounds, never beating the fast tier's own result. Undoing a
// fast-tier charge to try a Dijkstra alternative, unconditionally, for tens
// of thousands of nets in one pass is the multi-net version of the exact
// anti-pattern selective rip-up exists to prevent -- Dijkstra's larger
// flexibility just made the stampede worse, not better, with no supervision.
// Fixed by applying the cleanup pass's own safety check (try, compare local
// overflow via overflowOverUnion, revert if worse) to escalation itself, so
// a net's move to the slow tier can never make the design worse, only equal
// or better. See the comment at phase B's loop for the full account.
//
// Final result, total overflow / scored wirelength, verified against all
// three ISPD benchmarks (0 disconnected/incomplete/unrouted/malformed nets
// in every case):
//
//   benchmark   proute            mroute            hroute
//   adaptec1    221352 / 6111546  218650 / 6837420  178320 / 7194312
//   newblue1     58584 / 5546098   94060 / 6079307   42982 / 6635438
//   bigblue1    309822 / 6445711  346494 / 7008322  301296 / 7558074
//
// Beats every prior router's overflow on all three benchmarks -- the first
// time any router here has done that, rather than winning on some and
// losing on others. Confirms the escalation idea: reactively finding which
// *nets* the cheap tier can't legalize, rather than guessing which whole
// *design* favors which algorithm, gets the benefit of a real maze search
// where it matters and the speed of pattern candidates everywhere else.
// The cost is real, though -- 171-722s per benchmark, and every run here
// hit its round cap while still improving, meaning more slow rounds would
// likely still help further. Wirelength stays higher than proute's
// everywhere, continuing the same overflow-for-wirelength trade every
// router since the early-warning curve has made.
//
// Later ported from mroute.cpp: negotiateWire's price update was unclamped
// and could compound std::exp(...) past DBL_MAX to literal infinity under
// sustained deep overflow on one edge -- inf is never "<" a search
// region's own infinity sentinel, so the slow tier's Dijkstra can't relax
// that edge, finds no path, and mroute's version of this bug called
// fail(), exiting the whole process. hroute shares the identical
// price-update code, so the same failure was reachable here too (see
// testPriceClampPreventsInfinity), even though it was mroute's own layer-
// range experiment that first exposed it on real data. Fixed the same
// way: clamp growth at kForbiddenPrice, the same finite deterrent a
// hard-blocked edge already gets. Effect on the three benchmarks was
// small and mixed, as expected from a correctness fix that only fires on
// edges already deep in pathological overflow, not a tuning change:
//
//   benchmark   hroute (before)    hroute (clamped)
//   adaptec1    178320 / 7194312   174186 / 7152894   -- improves
//   newblue1     42982 / 6635438    42642 / 6628179   -- improves
//   bigblue1    301296 / 7558074   302770 / 7476917   -- slightly worse
//
// All three re-verified legal via gr_verify and cross-checked against the
// official eval2008.pl evaluator (exact agreement on total overflow and
// wirelength in every case).
//
// Build:
//     clang++ -std=c++17 -O2 -Wall -Wextra -o hroute hroute.cpp
//
// Use:
//     ./hroute benchmark.gr solution.route
//     ./hroute --selftest
//
// Environment variables (all optional):
//     HROUTE_EPS=<float>          fast-tier step size epsilon, default 0.02
//     HROUTE_THRESHOLD=<float>    fast-tier early-warning curve start,
//                                 default 0.2
//     HROUTE_POWER=<float>        fast-tier curve escalation power, default 2.5
//     HROUTE_FAST_ROUNDS=<int>    max phase-A (fast tier) rounds, default 30
//     HROUTE_SLOW_ROUNDS=<int>    max phase-B (escalation) rounds, default 30
//     HROUTE_CLEANUP_THRESHOLD=<float>, HROUTE_CLEANUP_PASSES=<int>
//                                 phase A's cleanup pass, same as nproute's
//                                 (defaults 0.5 / 30)
//     HROUTE_MAX_MARGIN=<int>     slow-tier Dijkstra search margin cap,
//                                 same as mroute's (default 6)
//     HROUTE_TRACE=1              print each round's overflow, the cleanup
//                                 pass's before/after, and phase B's
//                                 accepted/rejected counts, to stderr

